let evSeq = 0;
function ev(processId: string, daysAgo: number, title: string, source: ProcessEvent["source"], description?: string, important = false): ProcessEvent {
  evSeq += 1;
  return {
    ...o,
    id: `mov_${String(evSeq).padStart(3, "0")}`,
    processId,
    at: daysFromNowISO(-daysAgo, 9 + (evSeq % 8), (evSeq * 11) % 60),
    title,
    description,
    source,
    important,
  };
}

